
-- PostgreSQL Source Database Schema
-- AWS End-to-End Data Engineering Pipeline

CREATE SCHEMA IF NOT EXISTS devtalk;

CREATE TABLE devtalk.customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    country VARCHAR(50) NOT NULL
);

CREATE TABLE devtalk.products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    price NUMERIC(10,2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 100
);

CREATE TABLE devtalk.orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT orders_customer_id_fkey
        FOREIGN KEY (customer_id)
        REFERENCES devtalk.customers(customer_id),

    CONSTRAINT orders_product_id_fkey
        FOREIGN KEY (product_id)
        REFERENCES devtalk.products(product_id)
);
